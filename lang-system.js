// Get current language from localStorage
function getLang() {
    return localStorage.getItem('lang') || 'en';
}

// Set language to localStorage
function setLang(lang) {
    localStorage.setItem('lang', lang);
    translatePage();
}

// Get current theme from localStorage
function getTheme() {
    return localStorage.getItem('theme') || 'light';
}

// Set theme to localStorage
function setTheme(theme) {
    localStorage.setItem('theme', theme);
    if (theme === 'dark') {
        document.body.classList.add('dark-theme');
    } else {
        document.body.classList.remove('dark-theme');
    }
}

// Check if preferences are set
function hasPreferences() {
    return localStorage.getItem('preferencesSet') === 'true';
}

// Mark preferences as set
function markPreferencesSet() {
    localStorage.setItem('preferencesSet', 'true');
}

// Translate all elements with data-i18n attribute
function translatePage() {
    const lang = getLang();
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Translate placeholders
    const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
    placeholderElements.forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });
}

// Get translated text by key
function getTranslation(key) {
    const lang = getLang();
    if (translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    return translations['en'][key] || key;
}

// Initialize language and theme on page load
function initLangTheme() {
    const lang = getLang();
    const theme = getTheme();

    setTheme(theme);
    translatePage();
}

// Expose globally
window.getTranslation = getTranslation;

// Run on page load
if (typeof window !== 'undefined') {
    window.addEventListener('DOMContentLoaded', () => {
        if (hasPreferences()) {
            initLangTheme();
        }
    });
}
